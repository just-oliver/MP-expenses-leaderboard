"""Assetto Corsa track data files: surfaces.ini, map.png/map.ini, ui_track.json, outline."""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

SURFACES = [
    dict(KEY="ROAD", FRICTION=0.99, DAMPING=0, WAV="", WAV_PITCH=0, FF_EFFECT="NULL", DIRT_ADDITIVE=0,
         IS_VALID_TRACK=1, BLACK_FLAG_TIME=0, SIN_HEIGHT=0, SIN_LENGTH=0, IS_PITLANE=0, VIBRATION_GAIN=0, VIBRATION_LENGTH=0),
    dict(KEY="GRASS", FRICTION=0.6, DAMPING=0.1, WAV="grass.wav", WAV_PITCH=0, FF_EFFECT=1, DIRT_ADDITIVE=1,
         IS_VALID_TRACK=0, BLACK_FLAG_TIME=0, SIN_HEIGHT=0.03, SIN_LENGTH=0.5, IS_PITLANE=0, VIBRATION_GAIN=1.0, VIBRATION_LENGTH=1.5),
    dict(KEY="KERB", FRICTION=0.92, DAMPING=0, WAV="kerb.wav", WAV_PITCH=1.3, FF_EFFECT=1, DIRT_ADDITIVE=0,
         IS_VALID_TRACK=1, BLACK_FLAG_TIME=0, SIN_HEIGHT=0, SIN_LENGTH=0, IS_PITLANE=0, VIBRATION_GAIN=0, VIBRATION_LENGTH=0),
]


def write_surfaces(data_dir: Path):
    lines = []
    for i, s in enumerate(SURFACES):
        lines.append(f"[SURFACE_{i}]")
        lines += [f"{k}={v}" for k, v in s.items()]
        lines.append("")
    (data_dir / "surfaces.ini").write_text("\n".join(lines))


def write_map(track_dir: Path, centre: np.ndarray, closed: bool, max_size=1000, margin=20, drawing_size=10):
    xs, zs = centre[:, 0], centre[:, 2]
    extent = max(xs.max() - xs.min(), zs.max() - zs.min(), 1.0)
    scale = extent / (max_size - 2 * margin)  # metres per pixel
    x_off = -xs.min() + margin * scale
    z_off = -zs.min() + margin * scale
    width = int(np.ceil((xs.max() + x_off) / scale + margin))
    height = int(np.ceil((zs.max() + z_off) / scale + margin))
    pts = [((x + x_off) / scale, (z + z_off) / scale) for x, z in zip(xs, zs)]
    if closed:
        pts.append(pts[0])

    img = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    ImageDraw.Draw(img).line(pts, fill=(255, 255, 255, 255), width=drawing_size, joint="curve")
    img.save(track_dir / "map.png")
    (track_dir / "data" / "map.ini").write_text(
        "[PARAMETERS]\n"
        f"WIDTH={width}\nHEIGHT={height}\nMARGIN={margin}\nSCALE_FACTOR={scale:.6f}\n"
        f"X_OFFSET={x_off:.4f}\nZ_OFFSET={z_off:.4f}\nDRAWING_SIZE={drawing_size}\nMAX_SIZE={max_size}\n"
    )

    # UI outline (shown in the track selector)
    ow = 365
    s = (ow - 20) / max(width, height)
    outline = Image.new("RGBA", (ow, ow), (0, 0, 0, 0))
    ImageDraw.Draw(outline).line([(10 + x * s, 10 + y * s) for x, y in pts], fill=(255, 255, 255, 255), width=4, joint="curve")
    outline.save(track_dir / "ui" / "outline.png")


def run_direction(centre: np.ndarray, closed: bool) -> str:
    if not closed:
        return "A to B"
    x, z = centre[:, 0], centre[:, 2]
    # x east, z south: a positive shoelace sum is clockwise when viewed from above
    area = np.sum(x * np.roll(z, -1) - np.roll(x, -1) * z)
    return "clockwise" if area > 0 else "anticlockwise"


def write_ui(track_dir: Path, cfg, length, origin, run="clockwise"):
    lat, lng = origin
    ui = {
        "name": cfg.name,
        "description": cfg.description or "Generated from Google Street View imagery with sv2ac.",
        "tags": ["street", "generated", "circuit" if cfg.closed else "point to point"],
        "geotags": [f"{lat:.5f}", f"{lng:.5f}"],
        "country": cfg.country,
        "city": cfg.city,
        "length": f"{length:.0f}",
        "width": f"{cfg.road_width:.0f}",
        "pitboxes": str(cfg.pitboxes),
        "run": run,
        "author": cfg.author,
        "version": "0.1",
        "url": "",
        "year": 2026,
    }
    (track_dir / "ui" / "ui_track.json").write_text(json.dumps(ui, indent=2))


