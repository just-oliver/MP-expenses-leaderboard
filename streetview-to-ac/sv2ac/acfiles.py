def write_all(track_dir: Path, cfg, centre, length, origin, mesh_stats, sv_stats):
    write_surfaces(track_dir / "data")
    write_map(track_dir, centre, cfg.closed)
    write_ui(track_dir, cfg, length, origin, run_direction(centre, cfg.closed))
    sv = ", ".join(f"{k.replace('_', ' ')}: {v}" for k, v in sv_stats.items()) or "n/a"
    (track_dir / "NEXT_STEPS.txt").write_text(NEXT_STEPS.format(
        name=cfg.name, track_id=cfg.track_id, length=length, kind="loop" if cfg.closed else "point to point",
        panel_shader="ksPerPixelAT (alpha test)" if cfg.sky_mask else "ksPerPixel", sv=sv, **mesh_stats,
    ))
