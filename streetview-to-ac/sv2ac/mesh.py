"""Minimal mesh container + Wavefront OBJ/MTL writer."""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

import numpy as np

# KN5 meshes use 16-bit indices, so every object must stay below this.
MAX_VERTS = 60000


@dataclass
class MeshObject:
    name: str
    material: str
    positions: list = field(default_factory=list)
    uvs: list = field(default_factory=list)
    faces: list = field(default_factory=list)  # triangles, vertex indices (0-based, local)

    def add_vertex(self, p, uv) -> int:
        self.positions.append(p)
        self.uvs.append(uv)
        return len(self.positions) - 1

    def add_grid(self, grid_pos: np.ndarray, grid_uv: np.ndarray):
        """Add an (rows x cols) grid of vertices as quads.

        Faces are wound so the normal is (d/dcol) x (d/drow): with rows running
        forward along the track and cols running left->right, a flat strip faces up.
        """
        rows, cols = grid_pos.shape[:2]
        base = len(self.positions)
        self.positions.extend(grid_pos.reshape(-1, 3).tolist())
        self.uvs.extend(grid_uv.reshape(-1, 2).tolist())
        for r in range(rows - 1):
            for c in range(cols - 1):
                a = base + r * cols + c
                b = a + 1
                d = a + cols
                e = d + 1
                self.faces.append((a, b, e))
                self.faces.append((a, e, d))

    def normals(self) -> np.ndarray:
        p = np.asarray(self.positions, float)
        f = np.asarray(self.faces, int)
        n = np.zeros_like(p)
        if len(f):
            fn = np.cross(p[f[:, 1]] - p[f[:, 0]], p[f[:, 2]] - p[f[:, 0]])
            for k in range(3):
                np.add.at(n, f[:, k], fn)
        lens = np.linalg.norm(n, axis=1, keepdims=True)
        lens[lens == 0] = 1
        return n / lens


@dataclass
class Material:
    name: str
    texture: str  # relative path, e.g. "textures/asphalt.png"
    shader_hint: str = "ksPerPixel"
    alpha: bool = False


class Scene:
    def __init__(self):
        self.objects: list[MeshObject] = []
        self.materials: dict[str, Material] = {}

    def add_material(self, mat: Material):
        self.materials[mat.name] = mat

    def add(self, obj: MeshObject):
        if obj.faces:
            assert len(obj.positions) <= MAX_VERTS, f"{obj.name} has {len(obj.positions)} vertices"
            self.objects.append(obj)

    def stats(self):
        return {
            "objects": len(self.objects),
            "vertices": sum(len(o.positions) for o in self.objects),
            "triangles": sum(len(o.faces) for o in self.objects),
        }

    def write_obj(self, obj_path: Path):
        obj_path = Path(obj_path)
        mtl_path = obj_path.with_suffix(".mtl")
        with open(mtl_path, "w") as m:
            for mat in self.materials.values():
                m.write(f"newmtl {mat.name}\nKa 1 1 1\nKd 1 1 1\nKs 0 0 0\nd 1\nillum 1\nmap_Kd {mat.texture}\n")
                if mat.alpha:
                    m.write(f"map_d {mat.texture}\n")
                m.write("\n")
        with open(obj_path, "w") as f:
            f.write("# generated by sv2ac - units: metres, Y up, X east, Z south\n")
            f.write(f"mtllib {mtl_path.name}\n")
            vo = 1
            for o in self.objects:
                p = np.asarray(o.positions)
                uv = np.asarray(o.uvs)
                n = o.normals()
                f.write(f"o {o.name}\n")
                f.writelines(f"v {x:.4f} {y:.4f} {z:.4f}\n" for x, y, z in p)
                f.writelines(f"vt {u:.5f} {v:.5f}\n" for u, v in uv)
                f.writelines(f"vn {x:.4f} {y:.4f} {z:.4f}\n" for x, y, z in n)
                f.write(f"usemtl {o.material}\ns 1\n")
                for a, b, c in o.faces:
                    a, b, c = a + vo, b + vo, c + vo
                    f.write(f"f {a}/{a}/{a} {b}/{b}/{b} {c}/{c}/{c}\n")
                vo += len(p)
